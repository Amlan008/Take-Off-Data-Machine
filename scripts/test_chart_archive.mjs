import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {gunzipSync} from 'node:zlib';
const context={Blob,Response,CompressionStream,console};vm.createContext(context);
vm.runInContext(await readFile(new URL('../chart-archive.js',import.meta.url),'utf8'),context);
const api=context.ChartArchive;
const entry={path:'2026101600',valid_time:'2026-10-16T00:00:00Z',published_at:'2026-10-16T00:35:00Z'};
const manifest={version:1,generated_at:entry.published_at,surface:[entry],upper:[entry],levels_hpa:[850,500]};
assert.equal(api.plan(manifest,null).snapshots.length,2);
assert.equal(api.plan(manifest,{kind:'surface',path:entry.path}).snapshots.length,1);
assert.ok(!api.plan(manifest,null).files.some(f=>f.path.includes('shading')));
assert.ok(api.plan(manifest,null,true).files.some(f=>f.path.includes('shading')));
assert.throws(()=>api.plan({...manifest,surface:[{...entry,path:'../../secret'}]},null));
assert.throws(()=>api.plan({...manifest,levels_hpa:['../../x']},null));
let active=0,maximum=0,progress=0;
const read=async path=>{active++;maximum=Math.max(maximum,active);await new Promise(r=>setTimeout(r,1));active--;if(/features(?:-v5)?\.geojson$/.test(path))throw Error('legacy unavailable');return path.endsWith('metadata.json')?entry:{type:'FeatureCollection',features:[]};};
const archive=await api.collect(manifest,{read,progress:(done)=>{progress=done;}});
assert.ok(maximum<=3);assert.equal(progress,api.plan(manifest,null).files.length);
assert.equal(archive.missing_optional_files.length,4);
assert.ok(api.plan(manifest,null).files.some(f=>f.path.endsWith('features-v5.geojson')&&!f.required));
assert.equal(archive.format,'weather-machine-research-archive');
const packed=await api.encode(archive);assert.equal(packed.extension,'.json.gz');
const roundtrip=JSON.parse(gunzipSync(Buffer.from(await packed.blob.arrayBuffer())));
assert.equal(roundtrip.snapshots.length,2);
await assert.rejects(api.collect(manifest,{read:async()=>{throw Error('404');}}),/Archive incomplete/);
await assert.rejects(api.collect(manifest,{read:async p=>p.endsWith('metadata.json')?{...entry,published_at:'changed'}:{}}),/Publication changed/);
context.CompressionStream=undefined;
assert.equal((await api.encode(archive)).extension,'.json');
console.log('Archive scope, optional/required failures, publication checks, bounded concurrency and gzip round-trip passed.');
